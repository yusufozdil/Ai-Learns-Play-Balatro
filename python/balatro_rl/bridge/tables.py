_PACK_RE = re.compile(r"^p_(arcana|celestial|spectral|standard|buffoon)_(normal|jumbo|mega)_\d+$")
_PACK_KIND = {
    "arcana": "Arcana",
    "celestial": "Celestial",
    "spectral": "Spectral",
    "standard": "Standard",
    "buffoon": "Buffoon",
}


def pack_spec(key: str) -> dict:
    """Booster key (``p_buffoon_jumbo_1``) -> engine ``PackSpec`` JSON."""
    m = _PACK_RE.match(key)
    if not m:
        raise KeyError(f"unknown booster key {key!r}")
    return {"kind": _PACK_KIND[m.group(1)], "size": m.group(2).capitalize()}
